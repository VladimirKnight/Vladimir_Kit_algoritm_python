rating = int(input("Введите рейтинг (от 1 до 10): "))

match rating:
    
    case 9 | 10:
        print("Отличный продукт! 🌟 Настоятельно рекомендую!")
    case 7 | 8:
        print("Хороший продукт 🙂 Неплохо подойдет")
    
    case 5 | 6:
        print("Средний продукт 😐 Можно попробовать")
    
    case 1 | 2 | 3 | 4:
        print("Плохой продукт ❌ Не рекомендую")

    case _:
        print("Надо ввести число от 1 до 10!")