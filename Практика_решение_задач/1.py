DAY_HOURS = 24
#в сутках 24 часа

from_start = 0.2
#1/5 от того что времени что осталось до конца

hour = DAY_HOURS - (DAY_HOURS / (from_start + 1))
#Из 24 вычитаем 24 / 1.2 (20) получаем 4.
#1.2 потому что 1/5 от того что времени что осталось до конца, значит всего в сутках 6/5 времени = 1.2

print(f"Сейчас {hour} часа(ов)")